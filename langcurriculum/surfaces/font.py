"""A 5x7 bitmap font, written out so that rasterizing needs nothing installed.

The raster surface has to produce the same bytes on every machine, and a font
loaded from the host is the fastest way to lose that: hinting, versions and
substitution all differ, and the digest of a rendered episode would stop being a
property of the episode. So the glyphs live here, as data, and the rasterizer has
no dependencies at all.

The cost is coverage. This is printable ASCII plus the two symbols the curriculum
actually emits, which was measured rather than guessed — see
:func:`langcurriculum.surfaces.raster.coverage`. Anything else renders as a
hollow box and is reported in the transcode's
:class:`~langcurriculum.surfaces.content.Fidelity`, because a lesson whose answer
turns on a character the font does not have is not answerable from the image and
should be excluded rather than quietly rendered wrong.
"""

