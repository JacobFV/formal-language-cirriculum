def glyph(ch: str) -> tuple[str, ...]:
    """The bitmap for a character, or the missing-glyph box."""
    return GLYPHS.get(ch, MISSING)


def covers(text: str) -> tuple[str, ...]:
    """The distinct characters of ``text`` this font has no glyph for."""
    return tuple(sorted({c for c in text if c not in GLYPHS and c not in "\n\t"}))
